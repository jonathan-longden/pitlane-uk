/**
 * Seed catalogue of UK car meets.
 *
 * Dates are expressed as an offset in days from "today" rather than as fixed
 * calendar dates, so the bundled catalogue never ages into an empty list while
 * there is no backend behind it. When a real API replaces this file (see
 * `src/data/repository.ts`), events will carry absolute timestamps instead.
 */

function pad(n: number): string {
  return n.toString().padStart(2, '0');
}

